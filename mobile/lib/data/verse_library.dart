import 'dart:convert';

import 'package:flutter/services.dart';

import 'verse_cadence.dart';

/// A public-domain Bible translation bundled with the app.
class Translation {
  /// Creates a translation description.
  const Translation({required this.id, required this.name, required this.notice});

  /// Short code shown in the UI and stored in settings, for example `BSB`.
  final String id;

  /// Full name, for example `Berean Standard Bible`.
  final String name;

  /// Copyright or trademark notice that must be shown with the text.
  final String notice;
}

/// One curated verse (or short passage) in every bundled translation.
class Verse {
  /// Creates a verse with its text in each translation.
  const Verse({required this.id, required this.reference, required this.texts});

  /// Stable identifier derived from the reference, for example `JHN_3_16`.
  final String id;

  /// Human-readable reference, for example `John 3:16`.
  final String reference;

  /// Verse text keyed by [Translation.id].
  final Map<String, String> texts;

  /// Returns the text in [translationId], or in the default translation if it is missing.
  String textIn(String translationId) =>
      texts[translationId] ?? texts[VerseLibrary.defaultTranslationId]!;
}

/// The verse data that ships inside the app.
///
/// The data lives in `assets/verses.json`, generated by `tools/build_verses.py`.
/// Nothing is ever downloaded: the app works fully offline.
class VerseLibrary {
  /// Creates a library from already-parsed data. Prefer [load] or [fromJson].
  const VerseLibrary({required this.translations, required this.verses});

  /// Parses the JSON format written by `tools/build_verses.py`.
  factory VerseLibrary.fromJson(Map<String, Object?> json) {
    final translations = [
      for (final t in (json['translations']! as List<Object?>).cast<Map<String, Object?>>())
        Translation(
          id: t['id']! as String,
          name: t['name']! as String,
          notice: t['notice']! as String,
        ),
    ];
    final verses = [
      for (final v in (json['verses']! as List<Object?>).cast<Map<String, Object?>>())
        Verse(
          id: v['id']! as String,
          reference: v['ref']! as String,
          texts: (v['text']! as Map<String, Object?>).cast<String, String>(),
        ),
    ];
    return VerseLibrary(translations: translations, verses: verses);
  }

  /// Path of the bundled data file.
  static const assetPath = 'assets/verses.json';

  /// Translation used when the user has not chosen one.
  static const defaultTranslationId = 'BSB';

  /// Loads the bundled data from [bundle] (the app's asset bundle by default).
  static Future<VerseLibrary> load([AssetBundle? bundle]) async {
    final raw = await (bundle ?? rootBundle).loadString(assetPath);
    return VerseLibrary.fromJson(jsonDecode(raw) as Map<String, Object?>);
  }

  /// All bundled translations, in display order.
  final List<Translation> translations;

  /// All curated verses, in rotation order.
  final List<Verse> verses;

  /// The verse for rotation [slot] (see [VerseCadence.slotContaining]). The list repeats once
  /// every verse has been shown.
  ///
  /// This is the rotation rule shared by every platform. Kotlin (`DailyVerse.kt`) and Swift
  /// (`VerseStore.swift`) implement the same calculation so the app, the Android wallpaper, the
  /// iOS widget and the Shortcuts action always show the same verse. Change all three together.
  Verse verseForSlot(int slot) => verses[slot % verses.length];

  /// The verse to show at [now] (the current time by default) for [cadence].
  Verse current(VerseCadence cadence, [DateTime? now]) =>
      verseForSlot(cadence.slotContaining(now ?? DateTime.now()));

  /// The translation with [id], or the first translation if there is no match.
  Translation translation(String id) =>
      translations.firstWhere((t) => t.id == id, orElse: () => translations.first);
}
